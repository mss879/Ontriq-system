/**
 * Writes supabase/migrations/0024_seed_catalog.sql from the built-in catalogue
 * in src/domain/check-types/builtin.ts, so the database starts with exactly
 * the check types the code tests. Run once when the built-ins change before a
 * release; after a migration is applied, add a new one instead of editing it.
 *   npx tsx scripts/gen-catalog-seed.ts
 */
import { writeFileSync } from "node:fs";
import { BUILTIN_CHECK_TYPES, BUILTIN_PACKAGES, DOCUMENT_CATEGORIES } from "../src/domain/check-types/builtin";
import { parseCheckTypeSchema } from "../src/domain/check-types/schema";

const builtin = BUILTIN_CHECK_TYPES.map((t) => ({ key: t.key, name: t.name, description: t.description, icon: t.icon, sort: t.sort, schema: parseCheckTypeSchema(t.schema) }));
const packages = BUILTIN_PACKAGES.map((p) => ({ ...p, checks: [...p.checks] }));

const json = (v: unknown) => JSON.stringify(v, null, 2);

const STATUSES: [string, string, string, string, string, number][] = [
  ["case_received", "intake", "Case Received", "Received", "Received", 10],
  ["documents_pending", "documents", "Documents Pending", "Documents required", "We need your documents", 20],
  ["document_review", "documents", "Document Review in Progress", "Under review", "Checking your documents", 25],
  ["pending_information", "documents", "Pending Information", "Information required", "We need more information", 30],
  ["returned_for_correction", "documents", "Returned for Correction", "Under review", "Checking your documents", 35],
  ["pre_qc_in_progress", "pre_qc", "Pre-QC in Progress", "Under review", "Checking your documents", 40],
  ["data_entry_in_progress", "data_entry", "Data Entry in Progress", "In progress", "Verification in progress", 50],
  ["verification_in_progress", "verification", "Verification in Progress", "Verification in progress", "Verification in progress", 60],
  ["partially_completed", "verification", "Partially Completed", "Partially completed", "Verification in progress", 65],
  ["pending_post_qc", "post_qc", "Pending Post-QC", "Quality review", "Verification in progress", 70],
  ["final_report_in_progress", "report", "Final Report in Progress", "Report in preparation", "Almost done", 80],
  ["pending_final_approval", "approval", "Pending Final Approval", "Awaiting approval", "Almost done", 90],
  ["report_completed", "approval", "Report Completed", "Report ready", "Complete", 95],
  ["report_released", "released", "Report Released", "Report available", "Complete", 100],
  ["on_hold", "intake", "On Hold", "On hold", "Paused", 110],
  ["cancelled", "cancelled", "Cancelled", "Cancelled", "Cancelled", 120],
];
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

const sql = `-- =============================================================================
-- 0024_seed_catalog.sql
-- Feature: the starting catalogue. Document categories with their guidance,
-- the seven built-in check types (version 1, published), three packages,
-- status wording for staff, clients and candidates, two request templates
-- and the default assignment rules. Everything stays editable in Settings.
-- Generated by scripts/gen-catalog-seed.ts from src/domain/check-types/builtin.ts;
-- tests/unit/check-types.test.ts checks the two match. Idempotent.
-- Package prices start at 0: set them in Settings → Packages.
-- Depends on: 0004_check_types, 0005_packages_templates, 0006_cases, 0016_assignment.
-- =============================================================================

-- Document categories
insert into public.document_categories (org_id, key, name, guide, sensitive, sort)
select o.id, x.key, x.name, x.guide, x.sensitive, x.sort
  from public.orgs o
 cross join jsonb_to_recordset($categories$${json(DOCUMENT_CATEGORIES)}$categories$::jsonb)
       as x(key text, name text, guide text, sensitive boolean, sort int)
on conflict (org_id, key) do nothing;

-- Built-in check types and their first published version
create temporary table _builtin as
select * from jsonb_to_recordset($builtin$${json(builtin)}$builtin$::jsonb)
  as x(key text, name text, description text, icon text, sort int, schema jsonb);

insert into public.check_types (org_id, key, name, description, icon, sort, is_builtin)
select o.id, b.key, b.name, b.description, b.icon, b.sort, true
  from public.orgs o cross join _builtin b
on conflict (org_id, key) do nothing;

insert into public.check_type_versions (org_id, check_type_id, version, schema, published_at, notes)
select ct.org_id, ct.id, 1, b.schema, now(), 'Built-in version 1'
  from public.check_types ct join _builtin b on b.key = ct.key
 where ct.is_builtin and ct.current_version_id is null
   and not exists (select 1 from public.check_type_versions v where v.check_type_id = ct.id);

update public.check_types ct set current_version_id = v.id
  from public.check_type_versions v
 where v.check_type_id = ct.id and v.version = 1 and ct.current_version_id is null;

-- Packages (prices 0 until Ontriq sets them)
create temporary table _packages as
select * from jsonb_to_recordset($packages$${json(packages)}$packages$::jsonb)
  as x(code text, name text, description text, tat_days int, checks jsonb, sort int);

insert into public.packages (org_id, code, name, description, tat_days, sort)
select o.id, p.code, p.name, p.description, p.tat_days, p.sort
  from public.orgs o cross join _packages p
on conflict (org_id, code) do nothing;

insert into public.package_items (org_id, package_id, check_type_id, unit_price, sort)
select pk.org_id, pk.id, ct.id, 0, (e.ord * 10)::int
  from _packages p
  join public.packages pk on pk.code = p.code and pk.owner_scope = 'org'
 cross join lateral jsonb_array_elements_text(p.checks) with ordinality as e(key, ord)
  join public.check_types ct on ct.org_id = pk.org_id and ct.key = e.key
on conflict (package_id, check_type_id) do nothing;

drop table _builtin;
drop table _packages;

-- Status wording: internal, client and candidate labels
insert into public.client_status_catalog (org_id, key, stage, internal_label, client_label, candidate_label, sort)
select o.id, s.key, s.stage::public.case_stage, s.internal_label, s.client_label, s.candidate_label, s.sort
  from public.orgs o
 cross join (values
${STATUSES.map(([k, st, i, c, cand, sort]) => `   (${q(k)}, ${q(st)}, ${q(i)}, ${q(c)}, ${q(cand)}, ${sort})`).join(",\n")}
 ) as s(key, stage, internal_label, client_label, candidate_label, sort)
on conflict (org_id, key) do nothing;

-- Request templates for the New case picker
insert into public.request_templates (org_id, name, description, package_id, process_type, priority, is_favourite)
select pk.org_id, t.name, t.description, pk.id, t.process_type::public.process_type, 'normal', t.favourite
  from (values
    ('Standard hire · client sends documents', 'NIC, education and employment. The client uploads the CV and certificates.', 'STANDARD', 'client_supplied', true),
    ('Senior hire · Ontriq collects documents', 'All seven checks. Ontriq contacts the candidate for documents.', 'COMPREHENSIVE', 'candidate_collected', true)
  ) as t(name, description, package_code, process_type, favourite)
  join public.packages pk on pk.code = t.package_code and pk.owner_scope = 'org'
 where not exists (select 1 from public.request_templates rt where rt.org_id = pk.org_id and rt.name = t.name);

-- Assignment rules
insert into public.assignment_rules (org_id) select id from public.orgs on conflict (org_id) do nothing;
`;

writeFileSync("supabase/migrations/0024_seed_catalog.sql", sql);
console.log(`Wrote supabase/migrations/0024_seed_catalog.sql (${builtin.length} check types, ${DOCUMENT_CATEGORIES.length} categories, ${packages.length} packages).`);
