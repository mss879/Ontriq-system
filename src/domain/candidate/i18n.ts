export const CANDIDATE_DICTS: Record<CandidateLang, CandidateDict> = { en, si, ta };

export function candidateDict(lang: CandidateLang): CandidateDict {
  return CANDIDATE_DICTS[lang] ?? en;
}

/** Fill {placeholders}. Unknown placeholders are left as they are. */
export function fmt(template: string, vars: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (whole, key: string) => (key in vars ? String(vars[key]) : whole));
}

/** A document category's name in the candidate's language, falling back to the database name. */
export function categoryLabel(t: CandidateDict, key: string | null | undefined, fallback?: string | null): string {
  const known = key ? (t.categories as Record<string, string>)[key] : undefined;
  return known ?? fallback ?? key ?? "";
}

/** A check type's name in the candidate's language (built-in keys only), else its label. */
export function checkLabel(t: CandidateDict, key: string | null | undefined, fallback: string): string {
  return (key && (t.checks as Record<string, string>)[key]) || fallback;
}

/** A candidate-safe timeline entry in the candidate's language; English titles from the database are the fallback. */
export function timelineTitle(
  t: CandidateDict,
  e: { kind: string; title: string; data: { to: string | null; category: string | null } },
  categoryNames: Record<string, string> = {},
): string {
  const category = categoryLabel(t, e.data.category, e.data.category ? categoryNames[e.data.category] : null);
  switch (e.kind) {
    case "stage_changed":
      return e.data.to === "pre_qc" ? t.timeline.stage_pre_qc : e.data.to === "verification" ? t.timeline.stage_verification : e.data.to === "report" ? t.timeline.stage_report : t.timeline.stage_other;
    case "document_uploaded":
      return category ? fmt(t.timeline.document_uploaded, { category }) : e.title;
    case "document_requested":
      return category ? fmt(t.timeline.document_requested, { category }) : e.title;
    case "created":
    case "candidate_invited":
    case "document_rejected":
    case "request_created":
    case "request_answered":
    case "request_reopened":
    case "consent_submitted":
    case "consent_accepted":
    case "consent_rejected":
      return t.timeline[e.kind];
    default:
      return e.title;
  }
}

/** Map an English message from the upload helpers to its translation (they only speak English). */
export function translateUploadMessage(t: CandidateDict, message: string): string {
  if (message.startsWith("Upload a PDF")) return t.errors.fileType;
  if (message.includes("25 MB")) return t.errors.fileSize;
  if (message.includes("looks empty")) return t.errors.fileEmpty;
  if (message.includes("photo is small")) return t.errors.warnSmall;
  if (message.includes("very dark")) return t.errors.warnDark;
  if (message.includes("didn't go through")) return t.errors.uploadFailed;
  return message;
}
